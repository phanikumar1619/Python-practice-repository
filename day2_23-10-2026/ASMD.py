# fixed values 
x,y = 10,20 


# run time values
a = int(input())
b = int(input())

# Addition

add1 = x + y
add2 = a + b

# Subtraction

sub1 = x - y
sub2 = a - b

# Multiplication

mul1 = x * y
mul2 = a * b

# Division

div1 = x / y
div2 = a / b

print("the Addition of fixed varibles", add1)
print("the Addition of runtime varibles", add2)

print("the Subtraction of fixed varibles", sub1)
print("the Subtraction of runtime varibles", sub2)

print("the Multiplication of fixed varibles", mul1)
print("the Multiplication of runtime varibles", mul2)

print("the Division of fixed varibles", div1)
print("the Division of runtime varibles", div2)